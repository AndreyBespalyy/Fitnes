const cap = (s: string) => (s ? s[0].toUpperCase() + s.slice(1) : s);

/** «Иванова Мария Сергеевна» → { first: «Мария», middle: «Сергеевна» }; «Павел Рябов» → { first: «Павел» } */
export function nameParts(full: string): { first: string; middle: string | null } {
  const w = full.trim().split(/\s+/).filter(Boolean);
  if (!w.length) return { first: '', middle: null };
  if (w.length === 1) return { first: cap(w[0]), middle: null };
  const p = w.findIndex((x, i) => i > 0 && PATR.test(x));
  if (p > 0) return { first: cap(w[p - 1]), middle: cap(w[p]) };
  const known = w.findIndex((x) => NAMES.has(x.toLowerCase()));
  if (known >= 0) return { first: cap(w[known]), middle: null };
  // Неизвестное имя: кто похож на фамилию — тот не имя
  if (SURNAME.test(w[0]) && !SURNAME.test(w[1])) return { first: cap(w[1]), middle: null };
  return { first: cap(w[0]), middle: null };
}

/** Обращение: имя и отчество, если есть; фамилию не называем */
export const addressName = (full: string) => { const n = nameParts(full); return n.middle ? `${n.first} ${n.middle}` : n.first; };
/** Только имя */
export const givenName = (full: string) => nameParts(full).first;
